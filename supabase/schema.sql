-- KithaLovers initial database schema
-- Run in Supabase Dashboard -> SQL Editor.
-- This migration is designed for PostgreSQL/Supabase and enables RLS on all user data.

create extension if not exists pgcrypto;

create type public.connection_intent as enum ('friendship', 'dating', 'both');
create type public.connection_status as enum ('pending', 'matched', 'declined');
create type public.report_status as enum ('open', 'reviewing', 'resolved', 'dismissed');

create table public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  display_name text not null default '',
  birth_date date,
  bio text not null default '',
  city text not null default '',
  country text not null default '',
  intent public.connection_intent not null default 'both',
  gender text,
  interested_in text[] not null default '{}',
  is_visible boolean not null default true,
  photo_url text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint display_name_length check (char_length(display_name) <= 80),
  constraint bio_length check (char_length(bio) <= 600),
  constraint not_future_birth_date check (birth_date is null or birth_date <= current_date)
);

create table public.interests (
  id bigint generated by default as identity primary key,
  name text not null unique,
  created_at timestamptz not null default now()
);

create table public.profile_interests (
  profile_id uuid not null references public.profiles(id) on delete cascade,
  interest_id bigint not null references public.interests(id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key (profile_id, interest_id)
);

create table public.connection_requests (
  id uuid primary key default gen_random_uuid(),
  sender_id uuid not null references public.profiles(id) on delete cascade,
  recipient_id uuid not null references public.profiles(id) on delete cascade,
  status public.connection_status not null default 'pending',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint no_self_connection check (sender_id <> recipient_id),
  constraint unique_connection_request unique (sender_id, recipient_id)
);

create table public.matches (
  id uuid primary key default gen_random_uuid(),
  user_one uuid not null references public.profiles(id) on delete cascade,
  user_two uuid not null references public.profiles(id) on delete cascade,
  created_at timestamptz not null default now(),
  constraint no_self_match check (user_one <> user_two),
  constraint canonical_match_order check (user_one < user_two),
  constraint unique_match unique (user_one, user_two)
);

create table public.messages (
  id uuid primary key default gen_random_uuid(),
  match_id uuid not null references public.matches(id) on delete cascade,
  sender_id uuid not null references public.profiles(id) on delete cascade,
  body text not null,
  created_at timestamptz not null default now(),
  read_at timestamptz,
  constraint message_body_length check (char_length(body) between 1 and 4000)
);

create table public.blocks (
  blocker_id uuid not null references public.profiles(id) on delete cascade,
  blocked_id uuid not null references public.profiles(id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key (blocker_id, blocked_id),
  constraint no_self_block check (blocker_id <> blocked_id)
);

create table public.reports (
  id uuid primary key default gen_random_uuid(),
  reporter_id uuid not null references public.profiles(id) on delete cascade,
  reported_id uuid not null references public.profiles(id) on delete cascade,
  reason text not null,
  details text not null default '',
  status public.report_status not null default 'open',
  created_at timestamptz not null default now(),
  constraint no_self_report check (reporter_id <> reported_id),
  constraint report_reason_length check (char_length(reason) between 2 and 100),
  constraint report_details_length check (char_length(details) <= 2000)
);

create index profiles_discovery_idx on public.profiles (is_visible, city);
create index requests_recipient_idx on public.connection_requests (recipient_id, status, created_at desc);
create index messages_match_created_idx on public.messages (match_id, created_at);
create index reports_status_idx on public.reports (status, created_at);

create or replace function public.set_updated_at()
returns trigger language plpgsql as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

create trigger profiles_updated_at before update on public.profiles
for each row execute function public.set_updated_at();
create trigger requests_updated_at before update on public.connection_requests
for each row execute function public.set_updated_at();

-- Create a basic profile automatically after auth signup.
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  insert into public.profiles (id, display_name)
  values (
    new.id,
    coalesce(
      nullif(trim(new.raw_user_meta_data ->> 'display_name'), ''),
      nullif(trim(new.raw_user_meta_data ->> 'full_name'), ''),
      split_part(coalesce(new.email, 'member'), '@', 1)
    )
  )
  on conflict (id) do nothing;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created_kithalovers on auth.users;
create trigger on_auth_user_created_kithalovers
after insert on auth.users
for each row execute procedure public.handle_new_user();

-- RLS: enable by default on every table.
alter table public.profiles enable row level security;
alter table public.interests enable row level security;
alter table public.profile_interests enable row level security;
alter table public.connection_requests enable row level security;
alter table public.matches enable row level security;
alter table public.messages enable row level security;
alter table public.blocks enable row level security;
alter table public.reports enable row level security;

-- Profiles: visible profiles can be discovered; owner can always read/edit own profile.
create policy "Visible profiles are discoverable" on public.profiles
for select to authenticated
using (is_visible = true or id = (select auth.uid()));
create policy "Users insert their own profile" on public.profiles
for insert to authenticated with check (id = (select auth.uid()));
create policy "Users update their own profile" on public.profiles
for update to authenticated using (id = (select auth.uid())) with check (id = (select auth.uid()));

create policy "Signed-in users read interests" on public.interests
for select to authenticated using (true);
create policy "Users manage their profile interests" on public.profile_interests
for all to authenticated
using (profile_id = (select auth.uid()))
with check (profile_id = (select auth.uid()));

-- A request can be created only by its sender; sender/recipient may view it.
create policy "Participants read connection requests" on public.connection_requests
for select to authenticated
using (sender_id = (select auth.uid()) or recipient_id = (select auth.uid()));
create policy "Users send connection requests" on public.connection_requests
for insert to authenticated
with check (sender_id = (select auth.uid()) and sender_id <> recipient_id);
create policy "Recipients update incoming requests" on public.connection_requests
for update to authenticated
using (recipient_id = (select auth.uid()))
with check (recipient_id = (select auth.uid()));

-- Match rows visible only to members of that match.
create policy "Members read their matches" on public.matches
for select to authenticated
using (user_one = (select auth.uid()) or user_two = (select auth.uid()));

-- Messages: only match participants can read; only sender can insert their own message.
create policy "Match members read messages" on public.messages
for select to authenticated
using (exists (
  select 1 from public.matches m
  where m.id = messages.match_id
    and ((m.user_one = (select auth.uid())) or (m.user_two = (select auth.uid())))
));
create policy "Match members send own messages" on public.messages
for insert to authenticated
with check (
  sender_id = (select auth.uid())
  and exists (
    select 1 from public.matches m
    where m.id = messages.match_id
      and (m.user_one = (select auth.uid()) or m.user_two = (select auth.uid()))
  )
  and not exists (
    select 1 from public.blocks b
    where (b.blocker_id = (select auth.uid()) and b.blocked_id = (
      select case when m.user_one = (select auth.uid()) then m.user_two else m.user_one end
      from public.matches m where m.id = messages.match_id
    ))
    or (b.blocked_id = (select auth.uid()) and b.blocker_id = (
      select case when m.user_one = (select auth.uid()) then m.user_two else m.user_one end
      from public.matches m where m.id = messages.match_id
    ))
  )
);

create policy "Users manage blocks they create" on public.blocks
for all to authenticated
using (blocker_id = (select auth.uid()))
with check (blocker_id = (select auth.uid()));
create policy "Users submit reports" on public.reports
for insert to authenticated
with check (reporter_id = (select auth.uid()) and reporter_id <> reported_id);
create policy "Users read reports they submitted" on public.reports
for select to authenticated
using (reporter_id = (select auth.uid()));

